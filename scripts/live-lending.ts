async function buildStack(options: { readonly withHire: boolean }): Promise<Stack> {
  const tradeConfig = resolveTradeConfig(process.env, {
    chainId: NETWORK.chainId,
    keyStore: KEY_STORE,
  });
  const rpcUrls = resolveLpRpcUrls(process.env, READER_NETWORK);
  const lp = await buildLpServerDeps({
    env: process.env,
    network: READER_NETWORK,
    rpcUrls,
    keyStore: KEY_STORE,
    venues: tradeConfig.venues,
  });
  const rails = resolveLpRailConfig(process.env);
  if (!rails.ok) {
    throw new Error(
      `The LP manipulation rails are unset (${rails.failure.keys.join(", ")}); a guard whose `
        + "swaps have no slippage floor must not run.",
    );
  }
  const lending = await buildLendingServerDeps({
    env: process.env,
    network: READER_NETWORK,
    lpVenue: {
      routerV3: lp.addresses.routerV3,
      wbnb: lp.addresses.wbnb,
      quoterV2: lp.addresses.quoterV2,
      factoryV3: lp.addresses.factory,
      maxSagaSlippageBps: rails.config.maxSagaSlippageBps,
    },
  });
  if (lending === undefined) {
    throw new Error(
      "The lending deps did not build. `LENDING_ENABLED` resolved false after the boot gate "
        + "passed, which means the environment changed mid-run; refusing rather than guessing.",
    );
  }

  const agentStore = await createAgentStore();
  const journal = await createJournal();
  const nonceStore = await createNonceStore();
  const killswitch = await createKillSwitch();
  const provider = new AltanaProvider({ network: NETWORK, rpcUrls: [...rpcUrls] });
  const providerRegistry = createProviderRegistry([
    { network: NETWORK, options: { rpcUrls } },
  ]);
  const keyStoreReader = createKeyStoreReader({
    network: READER_NETWORK, rpcUrls, keyStore: KEY_STORE,
  });

  const dataPlaneUrl = process.env["DATA_PLANE_URL"]?.trim() ?? "";
  if (dataPlaneUrl === "") {
    throw new Error("DATA_PLANE_URL is required (the server dependency; .env carries it).");
  }
  const dataPlaneToken = process.env["DATA_PLANE_TOKEN"]?.trim() ?? "";

  // The hire deps are composed ONLY for `provision`, and exactly as
  // `src/index-server.ts` composes them — the same evidence reader, the same
  // headroom resolver, the same treasury. A second spelling of the funding
  // requirement would be a second number to keep honest.
  let hire: {
    readonly evidence: ReturnType<typeof createGrantEvidenceReader>;
    readonly nfpm: Address;
    readonly routerV3: Address;
    readonly wbnb: Address;
    readonly treasury: Address;
    readonly feeBps: number;
    readonly relayFeePerSubmitWei: bigint;
    readonly grantGasHeadroomWei: bigint;
  } | undefined;
  const relayFeePerSubmitWei: bigint | undefined = lp.lp.relayFeePerSubmitWei;
  let grantGasHeadroomWei: bigint | undefined;
  if (options.withHire) {
    if (relayFeePerSubmitWei === undefined) {
      throw new Error(
        "The LP wiring resolved no `relayFeePerSubmitWei`, so the hire's grant-gas headroom "
          + "cannot be sized. `HIRE_ENABLED` requires LP wiring (src/index-server.ts).",
      );
    }
    if (tradeConfig.feeTreasury === undefined) {
      throw new Error(
        "FEE_TREASURY_ADDRESS is required for the hire route (HIRE_ENABLED requires BNB "
          + "mainnet, DATABASE_URL, EXECUTION_MASTER_KEY, encrypted durable Postgres, "
          + "passkeys, LP wiring, and FEE_TREASURY_ADDRESS — src/index-server.ts).",
      );
    }
    if (!agentStore.durable || !agentStore.keyEncryptionConfigured) {
      throw new Error(
        "The hire route needs an encrypted, durable Postgres agent store "
          + "(DATABASE_URL + EXECUTION_MASTER_KEY). Refusing rather than sealing a session "
          + "key into a store that evaporates.",
      );
    }
    grantGasHeadroomWei = resolveHireGrantGasHeadroomWei(process.env, relayFeePerSubmitWei);
    hire = {
      evidence: createGrantEvidenceReader({
        network: { ...READER_NETWORK, keyStoreController: getAddress(NETWORK.keyStoreController) },
        rpcUrls,
        keyStoreReader,
      }),
      nfpm: lp.addresses.nfpm,
      routerV3: lp.addresses.routerV3,
      wbnb: lp.addresses.wbnb,
      treasury: tradeConfig.feeTreasury,
      feeBps: tradeConfig.feeBps ?? 0,
      relayFeePerSubmitWei,
      grantGasHeadroomWei,
    };
  }

  const execToken = `live-lending-${randomUUID()}`;
  const envSalt = process.env["EXECUTION_ENV_SALT"]?.trim();
  const config: ServerConfig = {
    chainId: NETWORK.chainId,
    network: NETWORK_LABEL,
    keyStore: KEY_STORE,
    execToken,
    operatorToken: `live-lending-op-${randomUUID()}`,
    trade: tradeConfig,
    ...(envSalt === undefined || envSalt === "" ? {} : { envSalt }),
  };

  const app = createServer({
    agentStore,
    journal,
    nonceStore,
    killswitch,
    providerRegistry,
    dataPlane: new HttpDataPlaneClient({
      baseUrl: dataPlaneUrl,
      ...(dataPlaneToken === "" ? {} : { token: dataPlaneToken }),
    }),
    lp: lp.lp,
    keyStoreReader,
    lending: {
      guards: lending.guards,
      settingsStore: lending.settingsStore,
      observations: lending.observations,
      readers: lending.readers,
      venue: lending.venue,
      intervalMs: lending.intervalMs,
      maxObservationAgeMs: lending.maxObservationAgeMs,
      maxSagaSlippageBps: lending.maxSagaSlippageBps,
      previewSecret: lending.previewSecret,
      ...(lending.routing === undefined ? {} : { routing: lending.routing }),
    },
    ...(hire === undefined ? {} : { hire }),
    config,
  });

  return {
    app,
    execToken,
    agentStore,
    journal,
    killswitch,
    provider,
    lending,
    lp,
    ...(hire === undefined ? {} : { hireEvidence: hire.evidence }),
    ...(grantGasHeadroomWei === undefined ? {} : { grantGasHeadroomWei }),
    async close(): Promise<void> {
      lp.evidence?.observer.stop();
      for (const closeable of [journal, nonceStore, killswitch, agentStore, lp.lp.store, lp.lp.settingsStore]) {
        try {
          await closeable.close();
        } catch {
          /* independent closes */
        }
      }
      await closeLendingServerDeps(lending);
    },
  };
}

