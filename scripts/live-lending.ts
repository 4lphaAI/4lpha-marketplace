/**
 * `live-lending` — the operator CLI for the Venus "guard on behalf"
 * (MARKETPLACE-LENDING-AGENT §12 / R2.25).
 *
 * It exists so the phase's LIVE GATES can be driven by a person rather than
 * described in a document. Wallet B holds a reserve (BNB partly swapped to USDT
 * and supplied to vUSDT) and calls `repayBorrowBehalf(A, …)` when account A's
 * health factor breaches. Every gate below moves real BNB on chain 56.
 *
 * ─── SUBCOMMANDS ──────────────────────────────────────────────────────────
 *
 *   census      READ-ONLY. Live gate 1. Re-probe every granted and refused
 *               selector in DEPLOYED bytecode, the Venus routing census against
 *               `VENUS_RECORDED_ROUTING`, `vUSDT.underlying()` and the pinned
 *               WBNB/USDT pool. One PASS/FAIL row per fact; a FAIL row is the
 *               grant refusal you would otherwise meet at S1.
 *   guardable   READ-ONLY. The guardable preview for account A: BOTH health
 *               factor bases with their protocol match flags, the markets, which
 *               debts this guard can actually repay, and — with a budget — the
 *               `reserveCapFloorWei` / `minimumCapDayWei` the hire must clear.
 *   preview     READ-ONLY. `checkLendingSizing` run locally, with the reserve
 *               split, the mint estimate, both cap floors AND
 *               `lendingExposureProduct` (cap × 7 days) printed BEFORE a grant
 *               exists — the FINDINGS (r) rule: the product, never the rate.
 *   provision   SPENDS. Live gate 2. Preview → the real S1 hire route → the
 *               on-chain grant with the owner key → convergence, with the grant
 *               cost MEASURED from B's balance either side.
 *   arm         SPENDS. Live gate 3. The owner-signed `lendingArm`: one batch
 *               that swaps the supply leg to USDT and mints vUSDT.
 *   status      READ-ONLY. The guard row and the worker's recorded view, PLUS a
 *               live reserve and account read, each labelled for which it is.
 *   settings    SPENDS (gas-free, but it changes what the worker does with
 *               money). Owner-signed `lendingSettings`, MERGED over the stored
 *               row — a flag changes only the field it names.
 *   retire      SPENDS. Live gate 7. Owner-signed `lendingRetire`, and it
 *               prints the outcome block honestly: HTTP 200 is NOT "retired".
 *   worker      One worker cycle. `--dry-run` IS THE DEFAULT here; a live cycle
 *               takes `--yes-live`. It drives `runLendingWorkerOnce` — the same
 *               entry `scripts/lending-worker.ts` runs — so every in-cycle gate
 *               stays in force.
 *
 * ─── THE SAFETY POSTURE, COPIED FROM `live-grid` / `live-venus` ───────────
 *
 * Every subcommand that can submit anything REFUSES without `--yes-live`, and
 * the refusal carries the figures it would have spent. A missing flag is never
 * a prompt. Unknown flags refuse the run before anything is constructed
 * (`scripts/lending-worker.ts`'s rule: a misspelled `--dry-run` silently
 * ignored would spend where the operator meant to rehearse).
 *
 * KEYS: the owner key is read through `readEnvValue` (process env, then `.env` /
 * `.env.local`, read-only), used to sign, and NEVER logged or persisted. This
 * file contains no key and generates none — the session key is generated by the
 * S1 route inside the plane and sealed by the store.
 *
 * BOOT GATES: `LENDING_ENABLED` (which itself requires `LP_ENABLED` and
 * `HIRE_ENABLED`), chain 56, and — for every command that touches the guard row
 * — `DATABASE_URL`. Each refusal quotes the boot rule it is enforcing rather
 * than guessing at a remedy.
 */
