async function commandGuardable(flags: Flags): Promise<void> {
  requireBoot("guardable");
  const account = needAddress(flags, "account");
  const { venue, readers, maxSagaSlippageBps } = await readOnlyLending();

  let reading;
  try {
    reading = await readers.readAccount(account, [venue.vUsdt, venue.vBnb]);
  } catch (error) {
    if (error instanceof LendingAccountTooComplexError) {
      console.log(
        `account ${account} is in more markets than this guard can price `
          + "(refusal `account-too-complex`); the guard is paused until it can.",
      );
      process.exitCode = 1;
      return;
    }
    throw error;
  }
  const view = venusBasisView(reading);
  const supported = (vToken: Address): boolean =>
    vToken.toLowerCase() === venue.vUsdt.toLowerCase()
    || vToken.toLowerCase() === venue.vBnb.toLowerCase();

  console.log(`guardable preview — account ${account}`);
  console.log(`block            : ${reading.blockNumber} (finalized)`);
  console.log(`protocolPaused   : ${reading.protocolPaused}`);
  console.log(
    `liquidation      : W ${view.pair.liquidationRisk.collateral} D ${view.pair.liquidationRisk.debt} `
      + `HF ${view.pair.liquidationRisk.healthFactor ?? "inf"} matched=${view.liquidationMatched}`,
  );
  console.log(
    `borrowing power  : W ${view.pair.borrowingPower.collateral} D ${view.pair.borrowingPower.debt} `
      + `HF ${view.pair.borrowingPower.healthFactor ?? "inf"} matched=${view.borrowingPowerMatched}`,
  );
  if (!view.liquidationMatched || !view.borrowingPowerMatched) {
    console.error(
      "PROTOCOL MISMATCH: the local reconstruction does not equal the protocol's own answer. "
        + "The guard FAILS CLOSED on this rather than acting on a smaller number.",
    );
  }
  let guardableDebt = false;
  console.log("markets:");
  for (const market of reading.markets) {
    const borrow = market.borrowCurrent ?? market.borrowStored;
    if (borrow === 0n && market.vTokenBalance === 0n && !market.collateralMember) continue;
    const isSupported = supported(market.vToken);
    if (borrow > 0n && isSupported) guardableDebt = true;
    console.log(
      `  ${market.vTokenSymbol.padEnd(8)} ${market.vToken} member=${market.collateralMember ? "y" : "n"} `
        + `borrow=${borrow} supported=${isSupported ? "yes" : "NO — this guard cannot repay it"} `
        + `repayPaused=${market.repayPaused}`,
    );
  }
  console.log(
    `guardable        : ${guardableDebt ? "yes" : "NO — no debt in a pinned market (vUSDT / vBNB)"}`,
  );

  const budgetWei = etherFlag(flags, "budget");
  if (budgetWei === undefined) {
    console.log(
      "\n(no --budget: the sizing half needs a budget, because `reserveCapFloorWei` is priced "
        + "on what the arm's swap would mint. Re-run with --budget <BNB> for the floors.)",
    );
    return;
  }
  const reserveBps = reserveBpsFlag(flags);
  const rescueReserveCount = intFlag(flags, "rescues", DEFAULT_LENDING_SETTINGS.rescueReserveCount);
  const reserveNativeWei = (budgetWei * BigInt(reserveBps)) / 10_000n;
  const supplyNativeWei = budgetWei - reserveNativeWei;
  const [supplyQuote, tierQuote] = await Promise.all([
    readers.quote({ tokenIn: venue.wbnb, tokenOut: venue.usdt, amountInWei: supplyNativeWei }),
    reserveNativeWei > 0n
      ? readers.quote({ tokenIn: venue.wbnb, tokenOut: venue.usdt, amountInWei: reserveNativeWei })
      : Promise.resolve(0n),
  ]);
  const floor = (quoted: bigint): bigint =>
    quoted <= 0n ? 0n : (quoted * BigInt(10_000 - maxSagaSlippageBps)) / 10_000n;
  const report = lendingPreviewReport({
    budgetWei,
    reserveBps,
    rescueReserveCount,
    mintUsdtWei: floor(supplyQuote),
    tierBuyBackUsdtWei: floor(tierQuote),
    capDayWei: null,
    reserveCapWei: null,
    usdt: venue.usdt,
    ttlSec: MAX_VENUS_SESSION_SECONDS,
  });
  console.log("\nsizing (priced at the floors — this is what a hire must clear):");
  for (const line of report) console.log(`  ${line}`);
  console.log(
    "\nNOTE: these floors are computed here from the SAME quoter the plane uses, but the "
      + "receipt that binds them to a hire comes from `GET /lending/guardable` in receipt mode, "
      + "which `provision` fetches for you.",
  );
}

