/* provision — live gate 2                                                    */
/* -------------------------------------------------------------------------- */

async function commandProvision(flags: Flags): Promise<void> {
  requireBoot("provision");
  const agentId = need(flags, "agent-id");
  const account = needAddress(flags, "account");
  const budgetWei = etherFlag(flags, "budget");
  if (budgetWei === undefined) throw new Error("--budget <BNB> is required.");
  const reserveBps = reserveBpsFlag(flags);
  const rescueReserveCount = intFlag(flags, "rescues", DEFAULT_LENDING_SETTINGS.rescueReserveCount);
  const ttlSec = intFlag(flags, "ttl-sec", MAX_VENUS_SESSION_SECONDS);
  const maxRepayUsdt = usdtFlag(flags, "max-repay-usdt");
  if (maxRepayUsdt === undefined) {
    throw new Error(
      "--max-repay-usdt <USDT> is required: `maxPerAction` must name one ceiling per pinned "
        + "debt market, and an empty list is a guard with no amount it may pay.",
    );
  }
  const maxRepayBnb = etherFlag(flags, "max-repay-bnb");

  const stack = await buildStack({ withHire: true });
  try {
    const venue = stack.lending.venue;
    // `resolveOwnerWallet` is the `provision-venus-agent` posture: under
    // EIP-7702 the wallet IS the owner's own EOA, so this DERIVES an address
    // and spends nothing. `--wallet` skips even that read.
    const wallet = optionalAddress(flags, "wallet")
      ?? (await stack.provider.resolveOwnerWallet({
        owner: authorityFromPrivateKey(ownerKey()),
      })).address;

    const marketsRaw = flags.get("markets");
    const debtMarkets =
      marketsRaw === undefined || marketsRaw === "true"
        ? [venue.vUsdt]
        : marketsRaw.split(",").map((entry) => {
            const trimmed = entry.trim();
            if (!isAddress(trimmed, { strict: false })) {
              throw new Error(`--markets contains "${trimmed}", which is not an address.`);
            }
            return getAddress(trimmed);
          });
    const pinsVBnb = debtMarkets.some((market) => market.toLowerCase() === venue.vBnb.toLowerCase());
    if (pinsVBnb && maxRepayBnb === undefined) {
      throw new Error(
        "--max-repay-bnb <BNB> is required when --markets pins vBNB: `enforceLendingV1Profile` "
          + "refuses settings with no ceiling for a pinned market.",
      );
    }

    /* ---- 1. The receipt-mode preview. READ ONLY. ------------------------- */
    const query = new URLSearchParams({
      account,
      budgetWei: budgetWei.toString(10),
      reserveBps: String(reserveBps),
      maxPerActionUsdtWei: maxRepayUsdt.toString(10),
      rescueReserveCount: String(rescueReserveCount),
    });
    const preview = await perimeterGet(stack, `/lending/guardable?${query.toString()}`);
    if (preview.status !== 200) {
      show("preview REFUSED", preview);
      process.exitCode = 1;
      return;
    }
    const previewData = preview.body["data"] as Record<string, unknown> | undefined;
    const receipt = previewData?.["previewReceipt"];
    const sizing = previewData?.["sizing"] as Record<string, unknown> | undefined;
    show("preview", previewData);
    if (typeof receipt !== "string") {
      console.error(
        "\nThe preview returned NO receipt. `LENDING_PREVIEW_SECRET` is unset, and S1 is "
          + "FAIL-CLOSED on that (R3.8): the hire would refuse `preview-receipt-unavailable`. "
          + "Set the secret and re-run. Nothing was sent.",
      );
      process.exitCode = 1;
      return;
    }
    if (previewData?.["guardable"] !== true) {
      console.error(
        "\nThe account is NOT guardable (no debt in a pinned market, or the read refused). "
          + "Refusing to hire a guard with nothing to do. Nothing was sent.",
      );
      process.exitCode = 1;
      return;
    }

    const capDayWei = etherFlag(flags, "cap-day")
      ?? BigInt(String(sizing?.["minimumCapDayWei"] ?? "0"));
    const reserveCapWei = usdtFlag(flags, "reserve-cap")
      ?? BigInt(String(sizing?.["reserveCapFloorWei"] ?? "0"));
    if (capDayWei <= 0n || reserveCapWei <= 0n) {
      throw new Error(
        "The preview returned no cap floors and none were named. Pass --cap-day <BNB> and "
          + "--reserve-cap <USDT> explicitly, or fix the preview.",
      );
    }

    const report = lendingPreviewReport({
      budgetWei,
      reserveBps,
      rescueReserveCount,
      mintUsdtWei: BigInt(String(sizing?.["mintUsdtWei"] ?? "0")),
      tierBuyBackUsdtWei: 0n,
      capDayWei,
      reserveCapWei,
      usdt: venue.usdt,
      ttlSec,
    });
    console.log("\nWHAT THIS HIRE WOULD GRANT:");
    for (const line of report) console.log(`  ${line}`);

    /* ---- 2. The funding requirement, computed not quoted ----------------- */
    //
    // The SAME reader and the SAME headroom the S1 route uses — the one the
    // stack composed. A second spelling here would be a second number to keep
    // honest, and this is the number an operator funds wallet B against.
    const evidence = stack.hireEvidence;
    const headroomWei = stack.grantGasHeadroomWei;
    if (evidence === undefined || headroomWei === undefined) {
      throw new Error("The hire deps were not composed; `provision` cannot read the funding half.");
    }
    const funding = await evidence.readFunding(
      wallet, headroomWei, Math.floor(Date.now() / 1000),
    );
    show("funding requirement (wallet B)", funding);

    const balanceBefore = await stack.provider.getBalance({ address: wallet });
    console.log(`\nwallet B          : ${wallet}`);
    console.log(`balance before    : ${formatEther(balanceBefore)} BNB`);
    console.log(`debt markets      : ${debtMarkets.join(", ")}`);
    console.log(`session TTL       : ${ttlSec}s`);

    requireYesLive(
      "provision",
      flags,
      `consume an owner nonce, generate a session key inside the plane, and GRANT an on-chain `
        + `session on ${wallet} with native cap ${formatEther(capDayWei)} BNB/day and USDT cap `
        + `${formatUnits(reserveCapWei, 18)}/day for ${ttlSec}s. The grant itself costs the `
        + `KeyStore registration fee plus gas, paid by wallet B.`,
    );

    /* ---- 3. S1 ----------------------------------------------------------- */
    const settingsParams: SettingsParams = {
      triggerHf: (mantissaFlag(flags, "trigger-hf") ?? DEFAULT_LENDING_SETTINGS.triggerHf).toString(10),
      targetHf: (mantissaFlag(flags, "target-hf") ?? DEFAULT_LENDING_SETTINGS.targetHf).toString(10),
      maxPerAction: [
        ...(debtMarkets.some((m) => m.toLowerCase() === venue.vUsdt.toLowerCase())
          ? [{ token: venue.usdt as string, maxWei: maxRepayUsdt.toString(10) }]
          : []),
        ...(pinsVBnb && maxRepayBnb !== undefined
          ? [{ token: null, maxWei: maxRepayBnb.toString(10) }]
          : []),
      ],
      minSecondsBetweenActions: intFlag(flags, "min-seconds", LENDING_MIN_SECONDS_BETWEEN_ACTIONS),
      rescueReserveCount,
      ...(mantissaFlag(flags, "notify-below-hf") === undefined
        ? {}
        : { notifyOnlyBelowHf: (mantissaFlag(flags, "notify-below-hf") ?? 0n).toString(10) }),
    };
    const parsedSettings = parseLendingSettingsParams(settingsParams);
    if (!parsedSettings.ok) {
      throw new Error(`The settings this run would sign are invalid: ${parsedSettings.message}`);
    }

    const hireParams = {
      walletAddress: wallet,
      token: venue.usdt,
      capDayWei: capDayWei.toString(10),
      openNativeBudgetWei: budgetWei.toString(10),
      ttlSec,
      sizingPreset: "lending-v1",
      guardedAccount: account,
      debtMarkets,
      reserveCapWei: reserveCapWei.toString(10),
      reserveBps,
      settings: settingsParams,
      previewReceipt: receipt,
    };
    const envelope = await signOwnerAction("provisionAgent", agentId, hireParams);
    const s1 = await ownerPost(stack, `/agents/${agentId}/session`, envelope);
    show("S1 (POST /agents/:id/session)", s1);
    if (s1.status !== 200) {
      console.error("\nS1 refused. Nothing was granted. The session key, if any, was not used.");
      process.exitCode = 1;
      return;
    }

    /* ---- 4. The grant ---------------------------------------------------- */
    const agent = await stack.agentStore.getAgentById(agentId);
    const pending = agent?.pendingGrant ?? null;
    if (agent === null || pending === null) {
      console.error(
        "\nThe row carries no pending grant, so there is nothing to grant. Read the S1 body above.",
      );
      process.exitCode = 1;
      return;
    }
    const sessionKey = await stack.agentStore.getAgentSessionKey(agent.ownerAddress, agent.id);
    if (sessionKey === null) {
      console.error(
        "\nThe sealed session key could not be read back (EXECUTION_MASTER_KEY?). The grant is "
          + "NOT attempted: granting a key this process cannot later use would strand the hire.",
      );
      process.exitCode = 1;
      return;
    }
    console.log(
      `\ngranting — this signs with the OWNER key and costs gas. session ${pending.sessionAddress}, `
        + `${pending.permissions.calls.length} call rule(s), expiry ${new Date(pending.expiresAt * 1000).toISOString()}`,
    );
    const ownerAuthority = authorityFromPrivateKey(ownerKey());
    const ownerWallet = await stack.provider.resolveOwnerWallet({ owner: ownerAuthority });
    const granted = await stack.provider.grantSession({
      wallet: ownerWallet,
      owner: ownerAuthority,
      spec: pending.sessionSpec,
      agent: authorityFromPrivateKey(sessionKey),
    });
    const balanceAfter = await stack.provider.getBalance({ address: wallet });
    console.log(`granted           : publicKey ${granted.publicKey}`);
    console.log(`balance after     : ${formatEther(balanceAfter)} BNB`);
    console.log(
      `MEASURED GRANT COST: ${formatEther(balanceBefore - balanceAfter)} BNB `
        + `(record this in FINDINGS (bn) — live gate 2)`,
    );

    /* ---- 5. Convergence -------------------------------------------------- */
    const converged = await ownerGet(stack, agentId, `/agents/${agentId}/session`);
    show("convergence (GET /agents/:id/session)", converged);
    console.log(
      "\nA row still reading `provisioning` with `missing: [...]` is NOT a failure yet — the "
        + "convergence is caller-independent and the 60 s sweep re-runs it. `permissions-differ` "
        + "IS terminal: the relay's enumeration did not match the persisted set byte-for-byte.",
    );
  } finally {
    await stack.close();
  }
}

