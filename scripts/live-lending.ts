/**
 * The venue `buildLendingServerDeps` resolves, MINUS the stores.
 *
 * It exists because `census`, `guardable` and `preview` write nothing and need
 * no queue, and requiring a reachable Postgres to read a health factor would
 * make the cheapest gates the hardest to run. It performs the SAME two
 * derivations the wiring does — `vUSDT.underlying()` for USDT and the factory
 * read for the pinned pool — and any divergence between the two is a bug: the
 * BOOT remains the authority, and it refuses a deployment this helper would
 * merely report on.
 */
async function readOnlyLending(): Promise<{
  readonly venue: LendingVenue;
  readonly venusVenue: VenusVenue;
  readonly readers: LendingChainReaders;
  readonly rpcUrls: readonly string[];
  readonly maxSagaSlippageBps: number;
}> {
  const runtime = resolveLendingRuntimeConfig(process.env);
  // `resolveLpAddresses` takes the router and WBNB from its OPTIONS, not from
  // the environment — `LP_NFPM`, `LP_V3_FACTORY` and `LP_QUOTER_V2` are the
  // only three it reads itself. Passing neither made it report
  // "VENUE_PANCAKE_ROUTER_V3, VENUE_WBNB missing" no matter what was set, so
  // `census`, `preview` and `guardable` could never run at all. Both correct
  // call sites resolve the venue first and hand it in; this mirrors
  // `scripts/lp-worker.ts:294`.
  const routerV3Raw = (process.env["VENUE_PANCAKE_ROUTER_V3"] ?? "").trim();
  const wbnbRaw = (process.env["VENUE_WBNB"] ?? "").trim();
  const lpAddresses = resolveLpAddresses(process.env, {
    chainId: NETWORK.chainId,
    keyStore: KEY_STORE,
    ...(routerV3Raw === "" ? {} : { routerV3: getAddress(routerV3Raw) }),
    ...(wbnbRaw === "" ? {} : { wbnb: getAddress(wbnbRaw) }),
  });
  const rails = resolveLpRailConfig(process.env);
  if (!rails.ok) {
    throw new Error(
      "The LP manipulation rails are unset, so `maxSagaSlippageBps` — the ONE floor every "
        + `lending swap leg is derived from — has no value (${rails.failure.keys.join(", ")}).`,
    );
  }
  const rpcUrls = resolveLendingRpcUrls(process.env, READER_NETWORK.publicRpcUrl);
  const primeRaw = (process.env["VENUS_PRIME_ADDRESS"] ?? "").trim();
  const venusVenue: VenusVenue = {
    comptroller: VENUS_CORE_COMPTROLLER_56,
    vBnb: runtime.venue.vBnb,
    prime: primeRaw === "" ? VENUS_CORE_COMPTROLLER_56 : getAddress(primeRaw),
    treasury: runtime.venue.treasury,
  };

  const client = createPublicClient({
    chain: READER_NETWORK.chain,
    transport: http(rpcUrls[0] ?? READER_NETWORK.publicRpcUrl),
  });
  const usdt = getAddress(
    await client.readContract({
      address: runtime.venue.vUsdt,
      abi: VTOKEN_UNDERLYING_ABI,
      functionName: "underlying",
    }),
  );

  const base: LendingVenue = {
    vUsdt: runtime.venue.vUsdt,
    usdt,
    vBnb: runtime.venue.vBnb,
    routerV3: getAddress(lpAddresses.routerV3),
    wbnb: getAddress(lpAddresses.wbnb),
    quoterV2: getAddress(lpAddresses.quoterV2),
    factoryV3: getAddress(lpAddresses.factory),
    swapPool: getAddress(lpAddresses.routerV3),
    swapFeeTier: runtime.venue.swapFeeTier,
    treasury: runtime.venue.treasury,
  };
  const probe = createLendingChainReaders({
    network: READER_NETWORK, rpcUrls, venue: base, venusVenue,
  });
  const pool = await probe.readSwapPool();
  const venue: LendingVenue = { ...base, swapPool: pool.pool };
  return {
    venue,
    venusVenue,
    readers: createLendingChainReaders({
      network: READER_NETWORK, rpcUrls, venue, venusVenue,
    }),
    rpcUrls,
    maxSagaSlippageBps: rails.config.maxSagaSlippageBps,
  };
}

