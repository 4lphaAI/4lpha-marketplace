export type Flags = ReadonlyMap<string, string>;

/** `--a b`, `--a=b` and bare `--a` (which becomes `"true"`). */
export function parseFlags(argv: readonly string[]): Flags {
  const map = new Map<string, string>();
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === undefined || !arg.startsWith("--")) continue;
    const eq = arg.indexOf("=");
    if (eq > 0) {
      map.set(arg.slice(2, eq), arg.slice(eq + 1));
      continue;
    }
    const next = argv[i + 1];
    if (next !== undefined && !next.startsWith("--")) {
      map.set(arg.slice(2), next);
      i += 1;
    } else {
      map.set(arg.slice(2), "true");
    }
  }
  return map;
}

/** Every flag name the command does not know. Sorted, for a stable message. */
export function unknownFlags(
  command: LendingCliCommand,
  flags: Flags,
): readonly string[] {
  const known = new Set(LENDING_CLI_KNOWN_FLAGS[command]);
  return [...flags.keys()].filter((name) => !known.has(name)).sort();
}

export function assertKnownFlags(command: LendingCliCommand, flags: Flags): void {
  const unknown = unknownFlags(command, flags);
  if (unknown.length === 0) return;
  throw new Error(
    `Unknown flag(s) for \`${command}\`: ${unknown.map((name) => `--${name}`).join(", ")}. `
      + `Known: ${LENDING_CLI_KNOWN_FLAGS[command].map((name) => `--${name}`).join(", ")}. `
      + "Refusing to run — a misspelled flag on this CLI is one keystroke from spending, "
      + "so it is never silently ignored.",
  );
}

export function isYesLive(flags: Flags): boolean {
  return flags.get("yes-live") === "true";
}

/**
 * Whether THIS invocation can submit. `worker` rehearses unless asked not to.
 */
export function commandIsLive(command: LendingCliCommand, flags: Flags): boolean {
  if (!LENDING_CLI_LIVE_COMMANDS.has(command)) return false;
  if (command === "worker") return isYesLive(flags) && flags.get("dry-run") !== "true";
  return true;
}

/**
 * THE GATE, as a pure function: the refusal text, or `null` to proceed.
 *
 * `requireYesLive` is only the printing half. Keeping the decision here means
 * the offline suite tests the SAME predicate the CLI runs rather than a
 * paraphrase of it.
 */
export function yesLiveGate(input: {
  readonly command: LendingCliCommand;
  readonly flags: Flags;
  readonly chainId: number;
  readonly networkLabel: string;
  readonly wouldSpend: string;
}): string | null {
  if (!commandIsLive(input.command, input.flags)) return null;
  if (isYesLive(input.flags)) return null;
  return yesLiveRefusal(
    input.command, input.chainId, input.networkLabel, input.wouldSpend,
  );
}

/** The refusal text, so the test can assert it names the figures and the flag. */
export function yesLiveRefusal(
  command: LendingCliCommand,
  chainId: number,
  networkLabel: string,
  wouldSpend: string,
): string {
  return (
    `\nREFUSED: \`${command}\` acts for real on chain ${chainId} (${networkLabel}).\n`
    + `It would: ${wouldSpend}\n`
    + "Re-run with --yes-live if that is what you want. Nothing was sent."
  );
}

/**
 * The boot gates, as a PURE check that returns the refusal or `null`.
 *
 * Each message quotes the rule it enforces — `src/ops/config.ts`'s resolver for
 * the flag triple, `src/lending/wiring.ts` for `DATABASE_URL` and chain 56 —
 * because "lending is off" is a fact about the deployment and an operator who
 * is told which line refused can fix it in one step.
 */
export function checkBootGates(input: {
  /**
   * `TradeEnv`, not `NodeJS.ProcessEnv`, so an offline test can hand this a
   * plain record. `process.env` is assignable to it.
   */
  readonly env: TradeEnv;
  readonly chainId: number;
  readonly command: LendingCliCommand;
}): string | null {
  let enabled: boolean;
  try {
    enabled = resolveLendingEnabled(input.env);
  } catch (error) {
    // `resolveLendingEnabled` is also the ONE place `LP_ENABLED` and
    // `HIRE_ENABLED` are required (src/lending/wiring.ts's docstring), so its
    // own text is the most precise thing that can be said here.
    return error instanceof Error ? error.message : "LENDING_ENABLED is malformed.";
  }
  // The read-only probes run with the guard OFF, deliberately: they are how an
  // operator checks a deployment BEFORE enabling it (runbook gates 1 and 2).
  if (!enabled && !LENDING_CLI_STORELESS_COMMANDS.has(input.command)) {
    return (
      'LENDING_ENABLED is not "true". `live-lending` refuses on a deployment that has not '
      + "enabled the guard: every route it drives is registered only when `deps.lending` is "
      + "wired, so a run here would report 404s that mean \"off\", not \"broken\". "
      + "`census`, `preview` and `guardable` read the chain directly and DO run with the "
      + "guard off — check the deployment with those first."
    );
  }
  if (input.chainId !== 56) {
    return (
      `The lending guard is chain-56 only; this run resolves chain ${input.chainId}. `
      + "The selector census was taken on BNB mainnet and means nothing anywhere else "
      + "(src/lending/wiring.ts)."
    );
  }
  if (LENDING_CLI_STORELESS_COMMANDS.has(input.command)) return null;
  if ((input.env["DATABASE_URL"] ?? "").trim() === "") {
    return (
      "DATABASE_URL is unset. The lending guard row IS the worker's queue and the arm's "
      + "idle gate: a memory store here would accept an owner-signed arm the worker can "
      + "never see, and would evaporate on restart (src/lending/wiring.ts)."
    );
  }
  return null;
}

