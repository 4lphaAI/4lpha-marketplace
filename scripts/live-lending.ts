type SignedEnvelope = {
  readonly signed: Record<string, unknown>;
  readonly signature: Hex;
  readonly params: unknown;
};

async function signOwnerAction(
  action: OwnerActionType,
  agentId: string,
  params: unknown,
): Promise<SignedEnvelope> {
  const account = privateKeyToAccount(ownerKey());
  const nowSec = Math.floor(Date.now() / 1000);
  const envSalt = process.env["EXECUTION_ENV_SALT"]?.trim();
  const message: OwnerActionStruct = {
    owner: account.address,
    agentId,
    action,
    paramsHash: paramsHash(action, params),
    nonce: keccak256(stringToBytes(`live-lending-${randomUUID()}`)),
    issuedAt: BigInt(nowSec - 5),
    expiry: BigInt(nowSec + 120),
  };
  const signature = await account.signTypedData({
    domain: buildOwnerActionDomain(
      NETWORK.chainId,
      resolveDomainSalt({
        chainId: NETWORK.chainId,
        network: NETWORK_LABEL,
        ...(envSalt === undefined || envSalt === "" ? {} : { envSalt }),
      }),
    ),
    types: OWNER_ACTION_TYPES,
    primaryType: "OwnerAction",
    message,
  });
  return {
    signed: {
      owner: message.owner,
      agentId: message.agentId,
      action: message.action,
      paramsHash: message.paramsHash,
      nonce: message.nonce,
      issuedAt: message.issuedAt.toString(10),
      expiry: message.expiry.toString(10),
    },
    signature,
    params,
  };
}

type HttpResult = { readonly status: number; readonly body: Record<string, unknown> };

async function readBody(response: Response): Promise<HttpResult> {
  const text = await response.text();
  try {
    return { status: response.status, body: JSON.parse(text) as Record<string, unknown> };
  } catch {
    return { status: response.status, body: { raw: text } };
  }
}

async function perimeterGet(stack: Stack, path: string): Promise<HttpResult> {
  return readBody(
    await stack.app.request(path, {
      method: "GET",
      headers: { "x-exec-token": stack.execToken },
    }),
  );
}

