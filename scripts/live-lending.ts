async function commandSettings(flags: Flags): Promise<void> {
  requireBoot("settings");
  const agentId = need(flags, "agent-id");
  const stack = await buildStack({ withHire: false });
  try {
    const ownerAddress = privateKeyToAccount(ownerKey()).address;
    const agent = await stack.agentStore.getAgent(ownerAddress, agentId);
    if (agent === null) throw new Error(`No agent ${agentId} for owner ${ownerAddress}.`);
    const stored = await stack.lending.settingsStore.get(agent.ownerAddress, agent.id);
    const current = stored === null ? null : parseLendingSettingsParams(stored.params);
    const base: SettingsParams =
      current !== null && current.ok
        ? settingsToParams(current.value)
        : settingsToParams(DEFAULT_LENDING_SETTINGS);
    if (stored === null) {
      console.warn(
        "NOTE: no stored settings row; merging over DEFAULTS. Every field you do not name will "
          + "be a default, because `lendingSettings` is a FULL REPLACEMENT on the wire.",
      );
    }
    const next = applySettingsFlags(base, flags, stack.lending.venue.usdt);
    const parsed = parseLendingSettingsParams(next);
    if (!parsed.ok) throw new Error(`The merged settings are invalid: ${parsed.message}`);

    show("current (stored)", base);
    show("next (merged over the stored row)", next);
    console.log(`\ndigest now        : ${stored?.digest ?? "(none)"}`);
    console.log(`digest next       : ${lendingSettingsDigest(next)}`);

    requireYesLive(
      "settings",
      flags,
      "sign and store new lending settings. No gas is spent, but the worker recomputes this "
        + "digest every cycle and acts on it with the owner's money — thresholds, the rescue "
        + "ceiling and the cooldown all change what a live rescue will do.",
    );

    const envelope = await signOwnerAction("lendingSettings", agentId, next);
    const response = await ownerPost(stack, `/agents/${agentId}/lending/settings`, envelope);
    show("settings", response);
    if (response.status !== 200) process.exitCode = 1;
  } finally {
    await stack.close();
  }
}

