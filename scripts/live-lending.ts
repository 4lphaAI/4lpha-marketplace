function need(flags: Flags, name: string): string {
  const value = flags.get(name);
  if (value === undefined || value.trim() === "" || value === "true") {
    throw new Error(`--${name} is required.`);
  }
  return value.trim();
}

function needAddress(flags: Flags, name: string): Address {
  const raw = need(flags, name);
  if (!isAddress(raw, { strict: false })) {
    throw new Error(`--${name} is not a valid address.`);
  }
  return getAddress(raw);
}

function optionalAddress(flags: Flags, name: string): Address | undefined {
  const raw = flags.get(name);
  if (raw === undefined || raw === "true" || raw.trim() === "") return undefined;
  if (!isAddress(raw.trim(), { strict: false })) {
    throw new Error(`--${name} is not a valid address.`);
  }
  return getAddress(raw.trim());
}

function intFlag(flags: Flags, name: string, fallback: number): number {
  const raw = flags.get(name);
  if (raw === undefined || raw === "true") return fallback;
  const parsed = Number(raw);
  if (!Number.isInteger(parsed)) throw new Error(`--${name} must be an integer.`);
  return parsed;
}

function etherFlag(flags: Flags, name: string): bigint | undefined {
  const raw = flags.get(name);
  if (raw === undefined || raw === "true" || raw.trim() === "") return undefined;
  return parseEther(raw.trim());
}

function usdtFlag(flags: Flags, name: string): bigint | undefined {
  const raw = flags.get(name);
  if (raw === undefined || raw === "true" || raw.trim() === "") return undefined;
  // BSC-USDT carries 18 decimals, which is why every USDT figure in this phase
  // is an 18-decimal wei string and never a 6-decimal one.
  return parseUnits(raw.trim(), 18);
}

function mantissaFlag(flags: Flags, name: string): bigint | undefined {
  const raw = flags.get(name);
  if (raw === undefined || raw === "true" || raw.trim() === "") return undefined;
  return parseUnits(raw.trim(), 18);
}

/** `--reserve-pct 20` ⇒ 2000 bps. Bounded exactly where the policy bounds it. */
function reserveBpsFlag(flags: Flags): number {
  const raw = flags.get("reserve-pct");
  if (raw === undefined || raw === "true") return LENDING_RESERVE_BPS_DEFAULT;
  const pct = Number(raw);
  if (!Number.isFinite(pct)) throw new Error("--reserve-pct must be a percentage, e.g. 20.");
  const bps = Math.round(pct * 100);
  if (bps < LENDING_RESERVE_BPS_MIN || bps > LENDING_RESERVE_BPS_MAX) {
    throw new Error(
      `--reserve-pct must be between ${LENDING_RESERVE_BPS_MIN / 100} and `
        + `${LENDING_RESERVE_BPS_MAX / 100} (percent of the budget kept as BNB).`,
    );
  }
  return bps;
}

