async function printGuardStatus(
  stack: Stack,
  guard: LendingGuardRecord,
  ownerAddress: Address,
): Promise<void> {
  console.log(`\n=== agent ${guard.agentId} owner ${guard.ownerAddress} ===`);
  console.log(`status            : ${guard.status}${guard.hold === null ? "" : ` hold=${guard.hold}`}`);
  console.log(`guarded account A : ${guard.guardedAccount}`);
  console.log(`debt markets      : ${guard.debtMarkets.join(", ")}`);
  console.log(`budget / split    : ${formatEther(guard.budgetWei)} BNB @ ${guard.reserveBps} bps`);
  console.log(`reserve cap       : ${formatUnits(guard.reserveCapWei, 18)} USDT/day`);
  console.log(
    `arm               : tx ${guard.armTxHash ?? "-"} block ${guard.armBlock ?? "-"} `
      + `mint ${formatUnits(guard.mintUsdtWei, 18)} USDT`,
  );
  console.log(
    `claim             : seq ${guard.actionSeq} last `
      + `${guard.lastActionAtMs === null ? "-" : new Date(guard.lastActionAtMs).toISOString()}`,
  );

  const agent = await stack.agentStore.getAgent(guard.ownerAddress, guard.agentId);
  if (agent === null) {
    console.log("agent row         : ABSENT (the guard row outlived its agent)");
    return;
  }
  console.log(
    `session           : status ${agent.status} expiry `
      + `${agent.sessionFacts === null ? "-" : new Date(agent.sessionFacts.expiry * 1000).toISOString()}`,
  );

  // The RECORDED view — zero chain reads, and it says how stale it is.
  if (guard.ownerAddress.toLowerCase() === ownerAddress.toLowerCase()) {
    const view = await ownerGet(stack, guard.agentId, `/agents/${guard.agentId}/lending/view`);
    show("owner view (RECORDED by the worker — never a live read)", view.body["data"] ?? view.body);
  } else {
    console.log(
      "owner view        : skipped — the owner key in this environment does not own this row.",
    );
  }

  // The LIVE reads, labelled as such. The view above is what the worker wrote;
  // these two are what the chain says now, and the difference IS the staleness.
  const settings = await stack.lending.settingsStore.get(guard.ownerAddress, guard.agentId);
  const parsed = settings === null ? null : parseLendingSettingsParams(settings.params);
  const rescueReserveCount =
    parsed !== null && parsed.ok
      ? parsed.value.rescueReserveCount
      : DEFAULT_LENDING_SETTINGS.rescueReserveCount;
  try {
    const reserve = await stack.lending.readers.readReserve(agent.walletAddress);
    const tier = lendingTier({
      nativeBalanceWei: reserve.nativeBalance,
      rescueReserveCount,
      rescuesChargedInWindow: 0,
      outstandingArmNativeWei: 0n,
    });
    const capacity = lendingCapacity({
      reading: reserve,
      tier,
      slippageBps: stack.lending.maxSagaSlippageBps,
      tierToUsdtWei: 0n,
      usdtToNativeWei: 0n,
    });
    const retirePlan = planLendingRetire(reserve);
    console.log("\nreserve (LIVE, wallet B, one pinned finalized block):");
    console.log(`  block           : ${reserve.blockNumber}`);
    console.log(`  idle USDT       : ${formatUnits(reserve.usdtBalance, 18)}`);
    console.log(`  supplied USDT   : ${formatUnits(capacity.suppliedUsdtWei, 18)} (at exchangeRateStored)`);
    console.log(`  vUSDT balance   : ${reserve.vUsdtBalance}`);
    console.log(`  pool cash       : ${formatUnits(reserve.cash, 18)} USDT`
      + `${capacity.poolCashLow ? "   ⚠ below the supply — a full redeem cannot clear in one go" : ""}`);
    console.log(`  BNB tier        : ${formatEther(tier.tierBnbWei)} (floor ${formatEther(tier.floorWei)}, `
      + `${tier.reservedSubmissions} submission(s) reserved)`);
    console.log(`  allowances      : vUSDT ${reserve.usdtAllowanceToVUsdt} router ${reserve.usdtAllowanceToRouter}`);
    console.log(
      `  retire plan     : redeem ${formatUnits(retirePlan.redeemAmountWei, 18)} / swap-in `
        + `${formatUnits(retirePlan.swapInWei, 18)} USDT`
        + `${retirePlan.poolShort ? `   POOL-SHORT: ${formatUnits(retirePlan.remainderUsdtWei, 18)} would stay on Venus` : ""}`,
    );
  } catch (error) {
    console.warn(
      `\nreserve (LIVE)    : UNREADABLE — ${sanitizeMessage(error instanceof Error ? error.message : "unknown")}`,
    );
  }

  try {
    const reading = await stack.lending.readers.readAccount(
      guard.guardedAccount, guard.debtMarkets,
    );
    const view = venusBasisView(reading);
    console.log("\naccount A (LIVE):");
    console.log(`  block           : ${reading.blockNumber} (finalized)`);
    console.log(
      `  liquidation HF  : ${view.pair.liquidationRisk.healthFactor ?? "inf"} matched=${view.liquidationMatched}`,
    );
    console.log(
      `  borrowing HF    : ${view.pair.borrowingPower.healthFactor ?? "inf"} matched=${view.borrowingPowerMatched}`,
    );
    for (const market of reading.markets) {
      const borrow = market.borrowCurrent ?? market.borrowStored;
      if (borrow === 0n) continue;
      console.log(`  borrow          : ${market.vTokenSymbol} ${borrow} repayPaused=${market.repayPaused}`);
    }
  } catch (error) {
    console.warn(
      `\naccount A (LIVE)  : UNREADABLE — ${sanitizeMessage(error instanceof Error ? error.message : "unknown")}`,
    );
  }
}

