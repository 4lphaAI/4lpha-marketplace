async function commandArm(flags: Flags): Promise<void> {
  requireBoot("arm");
  const agentId = need(flags, "agent-id");
  const stack = await buildStack({ withHire: false });
  try {
    const ownerAddress = privateKeyToAccount(ownerKey()).address;
    const agent = await stack.agentStore.getAgent(ownerAddress, agentId);
    if (agent === null) throw new Error(`No agent ${agentId} for owner ${ownerAddress}.`);
    const guard = await stack.lending.guards.get(agent.ownerAddress, agent.id);
    if (guard === null) {
      throw new Error(
        "This agent has no lending guard row yet; the hire's convergence writes it. Run "
          + "`live-lending status --agent-id <id>` (which converges) and try again.",
      );
    }
    const stored = await stack.lending.settingsStore.get(agent.ownerAddress, agent.id);
    if (stored === null) {
      throw new Error(
        "No `lending_settings` row. The arm is a CONTINUATION of the settings the owner signed "
          + "at S1 and never a second admission (AUDIT P19), so there is nothing to arm with.",
      );
    }
    const budgetWei = BigInt(agent.sessionFacts?.hireSizing?.openNativeBudgetWei ?? "0");
    const reserveNativeWei = (budgetWei * BigInt(guard.reserveBps)) / 10_000n;

    console.log(`agent             : ${agent.id} owner ${agent.ownerAddress}`);
    console.log(`wallet B          : ${agent.walletAddress}`);
    console.log(`guarded account A : ${guard.guardedAccount}`);
    console.log(`guard status      : ${guard.status}${guard.hold === null ? "" : ` hold=${guard.hold}`}`);
    console.log(`debt markets      : ${guard.debtMarkets.join(", ")}`);
    console.log(
      `budget            : ${formatEther(budgetWei)} BNB ⇒ BNB tier ${formatEther(reserveNativeWei)} `
        + `/ supply leg ${formatEther(budgetWei - reserveNativeWei)} BNB`,
    );
    console.log(`settings digest   : ${stored.digest}`);
    const balanceBefore = await stack.provider.getBalance({ address: agent.walletAddress });
    console.log(`balance before    : ${formatEther(balanceBefore)} BNB`);

    requireYesLive(
      "arm",
      flags,
      `submit ONE batch under the standing session that swaps ${formatEther(budgetWei - reserveNativeWei)} `
        + `BNB to USDT and mints vUSDT, leaving ${formatEther(reserveNativeWei)} BNB as the gas tier. `
        + "The arm's msg.value meters against the native day cap.",
    );

    const envelope = await signOwnerAction("lendingArm", agentId, {
      settings: stored.params,
      budgetWei: budgetWei.toString(10),
      reserveBps: guard.reserveBps,
    });
    const response = await ownerPost(stack, `/agents/${agentId}/lending/arm`, envelope);
    show("arm", response);
    const balanceAfter = await stack.provider.getBalance({ address: agent.walletAddress });
    console.log(`\nbalance after     : ${formatEther(balanceAfter)} BNB`);
    console.log(`delta             : ${formatEther(balanceBefore - balanceAfter)} BNB`);
    if (response.status !== 200) process.exitCode = 1;
  } finally {
    await stack.close();
  }
}

