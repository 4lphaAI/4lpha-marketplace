/* The census — PURE comparison over facts a caller read                      */
/* -------------------------------------------------------------------------- */

export type CensusRow = {
  readonly name: string;
  readonly expected: string;
  readonly observed: string;
  readonly pass: boolean;
};

export type CensusObservation = {
  readonly blockNumber: bigint;
  /** Selector presence in DEPLOYED bytecode, keyed `"<target>:<signature>"`. */
  readonly selectorsPresent: ReadonlyMap<string, boolean>;
  readonly vUsdt: Address;
  readonly vBnb: Address;
  readonly usdtFromUnderlying: Address;
  readonly usdtFromBoot: Address;
  readonly routing: VenusRoutingCensus;
  readonly pool: { readonly address: Address; readonly liquidity: bigint; readonly token0: Address };
};

const sameAddress = (left: string, right: string): boolean =>
  left.toLowerCase() === right.toLowerCase();

/**
 * Turn one probe into PASS/FAIL rows.
 *
 * The GRANTED selectors must be PRESENT (a grant that names a selector the
 * bytecode does not carry is a rule that can never fire, and — worse — a rule
 * the operator believes bounds something). The REFUSED list is NOT asserted
 * absent: `redeem(uint256)` and `borrow(uint256)` are present in vUSDT and
 * always will be — what matters is that `lendingSessionSpec` never grants them,
 * which is a template property the offline suite pins, not a chain fact.
 * Printing them here keeps the two lists visible side by side.
 */
export function censusRows(observed: CensusObservation): readonly CensusRow[] {
  const rows: CensusRow[] = [];
  const selector = (target: Address, signature: string): void => {
    const key = `${target.toLowerCase()}:${signature}`;
    const present = observed.selectorsPresent.get(key) ?? false;
    rows.push({
      name: `granted ${signature} @ ${target}`,
      expected: `present (${toFunctionSelector(signature)})`,
      observed: present ? "present" : "ABSENT",
      pass: present,
    });
  };
  for (const signature of LENDING_VUSDT_GRANTED_SELECTORS) {
    selector(observed.vUsdt, signature);
  }
  for (const signature of LENDING_VBNB_GRANTED_SELECTORS) {
    selector(observed.vBnb, signature);
  }
  rows.push({
    name: "vUSDT.underlying() equals the boot-derived USDT",
    expected: observed.usdtFromBoot,
    observed: observed.usdtFromUnderlying,
    pass: sameAddress(observed.usdtFromBoot, observed.usdtFromUnderlying),
  });
  rows.push({
    name: `routing: claimVenus facet (census block ${VENUS_CENSUS_BLOCK})`,
    expected: VENUS_RECORDED_ROUTING.claimVenusFacet,
    observed: observed.routing.claimVenusFacet,
    pass: sameAddress(VENUS_RECORDED_ROUTING.claimVenusFacet, observed.routing.claimVenusFacet),
  });
  rows.push({
    name: "routing: Prime implementation",
    expected: VENUS_RECORDED_ROUTING.primeImplementation,
    observed: observed.routing.primeImplementation,
    pass: sameAddress(
      VENUS_RECORDED_ROUTING.primeImplementation,
      observed.routing.primeImplementation,
    ),
  });
  for (const [vToken, implementation] of observed.routing.vTokenImplementations) {
    rows.push({
      name: `routing: ${vToken} implementation`,
      expected: VENUS_RECORDED_ROUTING.vBep20Implementation,
      observed: implementation,
      pass: sameAddress(VENUS_RECORDED_ROUTING.vBep20Implementation, implementation),
    });
  }
  rows.push({
    name: "pinned WBNB/USDT pool carries liquidity",
    expected: "> 0",
    observed: `${observed.pool.liquidity} @ ${observed.pool.address} (token0 ${observed.pool.token0})`,
    pass: observed.pool.liquidity > 0n,
  });
  return rows;
}

