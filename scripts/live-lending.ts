/**
 * Narrow the worker's queue to ONE agent without touching the store.
 *
 * `runLendingWorkerOnce` has no per-agent filter — its queue IS
 * `listForWorker()` — so the alternative to this proxy is a cycle that also
 * drives every OTHER armed guard on the same database, which is not what an
 * operator running a single gate asked for. The proxy can only NARROW: every
 * other method is forwarded to the real store with the real receiver, so the
 * fence, the claim CAS and the cooldown are the store's own.
 */
function scopeGuardsToAgent(store: LendingGuardStore, agentId: string): LendingGuardStore {
  return new Proxy(store, {
    get(target, property): unknown {
      if (property === "listForWorker") {
        return async (): Promise<readonly LendingGuardRecord[]> =>
          (await target.listForWorker()).filter((row) => row.agentId === agentId);
      }
      const value: unknown = Reflect.get(target, property, target);
      return typeof value === "function"
        ? (value as (...args: readonly unknown[]) => unknown).bind(target)
        : value;
    },
  });
}

function logOutcome(outcome: LendingWorkerAgentOutcome): void {
  const parts = [
    `agent=${outcome.agentId}`,
    `action=${outcome.action}`,
    ...(outcome.condition === undefined ? [] : [`condition=${outcome.condition}`]),
    ...(outcome.market === undefined ? [] : [`market=${outcome.market}`]),
    ...(outcome.amountWei === undefined ? [] : [`amount=${outcome.amountWei}`]),
    ...(outcome.healthFactor === undefined ? [] : [`hf=${outcome.healthFactor ?? "inf"}`]),
    ...(outcome.consecutive === undefined ? [] : [`consecutive=${outcome.consecutive}`]),
    ...(outcome.effect === undefined ? [] : [`effect=${outcome.effect}`]),
  ];
  console.log(`[live-lending] ${parts.join(" ")} reason=${sanitizeMessage(outcome.reason)}`);
}

async function commandWorker(flags: Flags): Promise<void> {
  requireBoot("worker");
  if (flags.get("once") !== "true") {
    throw new Error(
      "`worker` runs exactly one cycle and takes --once explicitly. The daemon is "
        + "`npm run lending-worker`; this subcommand is for driving ONE gate.",
    );
  }
  const live = commandIsLive("worker", flags);
  const agentId = flags.get("agent-id");
  const stack = await buildStack({ withHire: false });
  try {
    const guards =
      agentId === undefined || agentId === "true"
        ? stack.lending.guards
        : scopeGuardsToAgent(stack.lending.guards, agentId);
    const queue = await guards.listForWorker();
    console.log(`queue             : ${queue.length} guard row(s)`);
    for (const row of queue) {
      console.log(
        `  ${row.agentId} status=${row.status}${row.hold === null ? "" : ` hold=${row.hold}`} `
          + `A=${row.guardedAccount}`,
      );
    }
    if (live) {
      requireYesLive(
        "worker",
        flags,
        `drive ONE LIVE cycle over ${queue.length} guard row(s). A dispatched rescue submits `
          + "`repayBorrowBehalf` under the standing session and spends the owner's reserve.",
      );
    } else {
      console.log(
        "\nREHEARSAL (the default): every branch reports what a live cycle WOULD record and "
          + "writes NOTHING — no observation, no claim, no action row, no snapshot, no journal "
          + "row and no submission. Chain reads still happen; they ARE the decision.",
      );
    }

    const deps: LendingWorkerDeps = {
      agentStore: stack.agentStore,
      journal: stack.journal,
      killswitch: stack.killswitch,
      provider: stack.provider,
      guards,
      settingsStore: stack.lending.settingsStore,
      observations: stack.lending.observations,
      readers: stack.lending.readers,
      venue: stack.lending.venue,
      intervalMs: stack.lending.intervalMs,
      maxObservationAgeMs: stack.lending.maxObservationAgeMs,
      agentConcurrency: stack.lending.agentConcurrency,
      maxSagaSlippageBps: stack.lending.maxSagaSlippageBps,
      now: Date.now,
      dryRun: !live,
      log: logOutcome,
      ...(live
        ? {
            reconcile: async (): Promise<void> => {
              await reconcile({
                provider: stack.provider,
                journal: stack.journal,
                resolveWallet: async (owner, id) => {
                  const agent = await stack.agentStore.getAgentById(id);
                  if (agent === null) return null;
                  if (agent.ownerAddress !== (owner as Address).toLowerCase()) return null;
                  return {
                    address: agent.walletAddress,
                    chainId: NETWORK.chainId,
                    ownerAddress: agent.ownerAddress,
                    custodyModel: agent.custodyModel,
                  };
                },
              });
            },
          }
        : {}),
    };
    const report = await runLendingWorkerOnce(deps);
    console.log(
      `\n[live-lending] cycle done outcomes=${report.outcomes.length} `
        + `reconciled=${report.reconciled} dry-run=${report.dryRun}`,
    );
    console.log(
      "ONE `--once` run against a freshly armed guard CANNOT fire: one cycle cannot produce two "
        + "observations, and the spacing is enforced against the RECORDED stamp, so two runs "
        + "against one lagging node cannot manufacture a confirmation.",
    );
  } finally {
    await stack.close();
  }
}

