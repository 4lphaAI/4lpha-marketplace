async function commandCensus(flags: Flags): Promise<void> {
  requireBoot("census");
  const { venue, venusVenue, rpcUrls, readers } = await readOnlyLending();
  const rpcOverride = flags.get("rpc-url");
  const url =
    rpcOverride !== undefined && rpcOverride !== "true" && rpcOverride.trim() !== ""
      ? rpcOverride.trim()
      : (rpcUrls[0] ?? READER_NETWORK.publicRpcUrl);
  const client = createPublicClient({ chain: READER_NETWORK.chain, transport: http(url) });
  const chainId = await client.getChainId();
  if (chainId !== 56) {
    throw new Error(`The configured RPC served chain ${chainId}, not 56. Nothing was probed.`);
  }
  const blockNumber = await client.getBlockNumber();

  const targets: readonly (readonly [Address, readonly string[]])[] = [
    [venue.vUsdt, LENDING_VUSDT_GRANTED_SELECTORS],
    [venue.vBnb, LENDING_VBNB_GRANTED_SELECTORS],
  ];
  const selectorsPresent = new Map<string, boolean>();
  for (const [target, signatures] of targets) {
    const code = (await client.getCode({ address: target })) ?? "0x";
    for (const signature of signatures) {
      const selector = toFunctionSelector(signature).slice(2).toLowerCase();
      selectorsPresent.set(
        `${target.toLowerCase()}:${signature}`,
        code.toLowerCase().includes(selector),
      );
    }
  }

  const usdtFromUnderlying = getAddress(
    await client.readContract({
      address: venue.vUsdt, abi: VTOKEN_UNDERLYING_ABI, functionName: "underlying",
    }),
  );
  const venusReaders = createVenusChainReaders({
    network: READER_NETWORK,
    rpcUrls: [url],
    venue: venusVenue,
    markets: [venue.vUsdt, venue.vBnb],
  });
  const routing = await venusReaders.readRoutingCensus([venue.vUsdt, venue.vBnb]);
  const pool = await readers.readSwapPool();

  const rows = censusRows({
    blockNumber,
    selectorsPresent,
    vUsdt: venue.vUsdt,
    vBnb: venue.vBnb,
    usdtFromUnderlying,
    usdtFromBoot: venue.usdt,
    routing,
    pool: { address: pool.pool, liquidity: pool.liquidity, token0: pool.token0 },
  });

  console.log(`live gate 1 — the lending census, re-probed at block ${blockNumber} on chain 56`);
  console.log(`rpc            : ${url}`);
  console.log(`vUSDT / vBNB   : ${venue.vUsdt} / ${venue.vBnb}`);
  console.log(`router / WBNB  : ${venue.routerV3} / ${venue.wbnb}`);
  console.log(`fee tier       : ${venue.swapFeeTier}`);
  console.log("");
  let failed = 0;
  for (const row of rows) {
    if (!row.pass) failed += 1;
    console.log(
      `[${row.pass ? "PASS" : "FAIL"}] ${row.name}\n`
        + `        expected ${row.expected}\n        observed ${row.observed}`,
    );
  }
  console.log("");
  console.log(
    `REFUSED SET (never granted by lendingSessionSpec; a template property, not a chain fact):\n  ${LENDING_REFUSED_SELECTORS.join(", ")}`,
  );
  console.log(`GRANTED SET: ${LENDING_GRANTED_SELECTORS.join(", ")}`);
  if ((process.env["VENUS_PRIME_ADDRESS"] ?? "").trim() === "") {
    console.warn(
      "\nWARNING: VENUS_PRIME_ADDRESS is unset, so the Prime implementation was read from the "
        + "Comptroller's own EIP-1967 slot and cannot match the recorded census. The lending "
        + "boot reads the SAME census and S1 asserts it, so a hire on this deployment will "
        + "refuse the grant. Set VENUS_PRIME_ADDRESS before live gate 2.",
    );
  }
  if (failed > 0) {
    console.error(
      `\n${failed} census row(s) FAILED. \`lendingSessionSpec\` asserts this census at S1, so a `
        + "grant on this deployment would be refused — re-take the census through the phase "
        + "process before hiring anything.",
    );
    process.exitCode = 1;
    return;
  }
  console.log("\nAll census rows PASS. Live gate 1 is satisfied for this block.");
}

