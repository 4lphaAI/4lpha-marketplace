/** The wire shape `parseLendingSettingsParams` accepts. */
type SettingsParams = {
  triggerHf: string;
  targetHf: string;
  maxPerAction: { token: string | null; maxWei: string }[];
  minSecondsBetweenActions: number;
  rescueReserveCount: number;
  notifyOnlyBelowHf?: string;
};

function settingsToParams(settings: LendingSettings): SettingsParams {
  return {
    triggerHf: settings.triggerHf.toString(10),
    targetHf: settings.targetHf.toString(10),
    maxPerAction: settings.maxPerAction.map((cap) => ({
      token: cap.token,
      maxWei: cap.maxWei.toString(10),
    })),
    minSecondsBetweenActions: settings.minSecondsBetweenActions,
    rescueReserveCount: settings.rescueReserveCount,
    ...(settings.notifyOnlyBelowHf === undefined
      ? {}
      : { notifyOnlyBelowHf: settings.notifyOnlyBelowHf.toString(10) }),
  };
}

function upsertCap(
  params: SettingsParams,
  token: string | null,
  maxWei: bigint,
): void {
  const key = token === null ? null : token.toLowerCase();
  const existing = params.maxPerAction.find(
    (cap) => (cap.token === null ? null : cap.token.toLowerCase()) === key,
  );
  if (existing === undefined) {
    params.maxPerAction.push({ token, maxWei: maxWei.toString(10) });
    return;
  }
  existing.maxWei = maxWei.toString(10);
}

/**
 * Apply the flags an operator named onto a settings object, MERGE-STYLE.
 *
 * `lendingSettings` is a FULL REPLACEMENT on the wire, so a CLI that built its
 * payload from defaults would silently reset every field the operator did not
 * mention — the `live-lp settings` discipline, and the reason this merges over
 * the STORED row rather than over `DEFAULT_LENDING_SETTINGS`.
 */
function applySettingsFlags(
  base: SettingsParams,
  flags: Flags,
  usdt: Address,
): SettingsParams {
  const next: SettingsParams = {
    ...base,
    maxPerAction: base.maxPerAction.map((cap) => ({ ...cap })),
  };
  const trigger = mantissaFlag(flags, "trigger-hf");
  if (trigger !== undefined) next.triggerHf = trigger.toString(10);
  const target = mantissaFlag(flags, "target-hf");
  if (target !== undefined) next.targetHf = target.toString(10);
  const notify = mantissaFlag(flags, "notify-below-hf");
  if (notify !== undefined) next.notifyOnlyBelowHf = notify.toString(10);
  if (flags.get("clear-notify-below-hf") === "true") delete next.notifyOnlyBelowHf;
  const minSeconds = flags.get("min-seconds");
  if (minSeconds !== undefined && minSeconds !== "true") {
    next.minSecondsBetweenActions = intFlag(flags, "min-seconds", LENDING_MIN_SECONDS_BETWEEN_ACTIONS);
  }
  const rescues = flags.get("rescues");
  if (rescues !== undefined && rescues !== "true") {
    next.rescueReserveCount = intFlag(flags, "rescues", DEFAULT_LENDING_SETTINGS.rescueReserveCount);
  }
  const usdtCeiling = usdtFlag(flags, "max-repay-usdt");
  if (usdtCeiling !== undefined) upsertCap(next, usdt, usdtCeiling);
  const bnbCeiling = etherFlag(flags, "max-repay-bnb");
  if (bnbCeiling !== undefined) upsertCap(next, null, bnbCeiling);
  return next;
}

